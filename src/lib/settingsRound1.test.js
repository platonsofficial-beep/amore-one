import { describe, expect, it } from 'vitest'
import { translate } from '../i18n/i18n'

describe('settings round 1 copy', () => {
  it('translates the audited Settings strings and keeps English', () => {
    expect(translate('Reservations', undefined, 'el')).toBe('Κρατήσεις')
    expect(translate('Schedule', undefined, 'el')).toBe('Πρόγραμμα')
    expect(translate('Tasks', undefined, 'el')).toBe('Εργασίες')
    expect(translate('Stock', undefined, 'el')).toBe('Απόθεμα')
    expect(translate('Suppliers', undefined, 'el')).toBe('Προμηθευτές')
    expect(translate('Insights', undefined, 'el')).toBe('Αναφορές')
    expect(translate('Connected', undefined, 'el')).toBe('Συνδεδεμένο')
    expect(translate('Version {{version}}', { version: 'v1.0.0-core' }, 'el')).toBe('Έκδοση v1.0.0-core')
    expect(translate('Bar', undefined, 'el')).toBe('Μπαρ')
    expect(translate('Service', undefined, 'el')).toBe('Σερβίρισμα')
    expect(translate('Kitchen', undefined, 'el')).toBe('Κουζίνα')
    expect(translate('Management', undefined, 'el')).toBe('Διοίκηση')
    expect(translate('Other', undefined, 'el')).toBe('Άλλο')
    expect(translate('{{count}} position', { count: 6 }, 'el')).toBe('6 θέσεις')
    expect(translate('{{count}} position', { count: 1 }, 'el')).toBe('1 θέση')
    expect(translate('Used by {{count}} employee', { count: 1 }, 'el')).toBe('Χρησιμοποιείται από 1 εργαζόμενο')
    expect(translate('Used by {{count}} employee', { count: 2 }, 'el')).toBe('Χρησιμοποιείται από 2 εργαζόμενους')
    expect(translate('Sun', undefined, 'el')).toBe('Κυρ')
    expect(translate('Sat', undefined, 'el')).toBe('Σαβ')
    expect(translate('From', undefined, 'el')).toBe('Από')
    expect(translate('Until', undefined, 'el')).toBe('Έως')
    expect(translate('Announcements', undefined, 'el')).toBe('Ανακοινώσεις')
    expect(translate('Checklists', undefined, 'el')).toBe('Λίστες ελέγχου')
    expect(translate("Couldn't load the business profile. Check your connection and try again.", undefined, 'el'))
      .toBe('Δεν φορτώθηκε το προφίλ καταστήματος. Έλεγξε τη σύνδεση και δοκίμασε ξανά.')
    expect(translate('PNG, JPG, WEBP, or SVG up to {{size}} KB.', { size: 256 }, 'el')).toBe('PNG, JPG, WEBP ή SVG έως 256 KB.')
    expect(translate('Manager Full Name', undefined, 'el')).toBe('Ονοματεπώνυμο υπευθύνου')
    expect(translate('New venue', undefined, 'el')).toBe('Νέο κατάστημα')
    expect(translate('Terrace', undefined, 'el')).toBe('Βεράντα')
    expect(translate('Lounge', undefined, 'el')).toBe('Σαλόνι')
    expect(translate('Garden', undefined, 'el')).toBe('Κήπος')
    expect(translate('Reception', undefined, 'el')).toBe('Υποδοχή')
    expect(translate('Host', undefined, 'el')).toBe('Οικοδεσπότης')
    expect(translate('Private', undefined, 'el')).toBe('Ιδιωτικός')
    expect(translate('Manage Staff →', undefined, 'el')).toBe('Διαχείριση προσωπικού →')
    expect(translate('Seatings, notifications & privacy', undefined, 'el')).toBe('Σερβιρίσματα, ειδοποιήσεις και απόρρητο')
    expect(translate('Manage seatings', undefined, 'el')).toBe('Διαχείριση σερβιρισμάτων')
    expect(translate('Seating list', undefined, 'el')).toBe('Λίστα σερβιρισμάτων')
    expect(translate('Clock-in reminders', undefined, 'el')).toBe('Υπενθυμίσεις έναρξης βάρδιας')
    expect(translate('Connected', undefined, 'en')).toBe('Connected')
    expect(translate('New venue', undefined, 'en')).toBe('New venue')
    expect(translate('{{count}} position', { count: 6 }, 'en')).toBe('6 positions')
    expect(translate('Used by {{count}} employee', { count: 1 }, 'en')).toBe('Used by 1 employee')
  })
})
